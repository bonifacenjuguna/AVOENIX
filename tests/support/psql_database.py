"""TEST-ONLY ``Database`` adapter that talks to a real PostgreSQL server through the ``psql`` client.

Purpose: in environments where psycopg cannot be installed (like the sandbox this foundation was built in)
the *SQL generated by PostgresBackend* can still be executed against a real PostgreSQL server. It is NOT used in
production (production uses ``PsycopgDatabase``), and it is not atomic across calls, so transaction-rollback
behaviour is not covered by tests that use it.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
from datetime import date, datetime
from typing import Any, Sequence

from intelligence.core.errors import ConflictError, StorageError


def literal(v: Any) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, (datetime, date)):
        v = v.isoformat()
    if isinstance(v, (dict, list)):
        v = json.dumps(v)
    s = str(v)
    if "\x00" in s:
        raise StorageError("NUL byte in parameter")
    return "'" + s.replace("'", "''") + "'"


def interpolate(sql: str, params: Sequence[Any]) -> str:
    parts = re.split(r"(%s)", sql)
    it = iter(params)
    out = []
    for p in parts:
        out.append(literal(next(it)) if p == "%s" else p)
    rest = list(it)
    if rest:
        raise StorageError("too many parameters")
    return "".join(out)


class PsqlDatabase:
    def __init__(self, host: str, port: int, dbname: str, user: str = "postgres"):
        if not shutil.which("psql"):
            raise StorageError("psql client not found")
        self.args = ["psql", "-X", "-q", "-A", "-t", "-h", host, "-p", str(port), "-U", user, "-d", dbname, "-v", "ON_ERROR_STOP=1"]

    def query(self, sql: str, params: Sequence[Any] = ()) -> list[dict[str, Any]]:
        full = interpolate(sql, params)
        stmt = full.strip().rstrip(";")
        wrapped = f"WITH q AS ({stmt}) SELECT coalesce(json_agg(q), '[]'::json) FROM q"
        proc = subprocess.run(self.args + ["-c", wrapped], capture_output=True, text=True, timeout=30)
        if proc.returncode != 0:
            if "duplicate key" in proc.stderr or "unique constraint" in proc.stderr:
                raise ConflictError("unique constraint violated")
            raise StorageError("psql error: " + proc.stderr.strip().splitlines()[-1][:300])
        text = proc.stdout.strip()
        return json.loads(text) if text else []

    def transaction(self):
        from contextlib import nullcontext
        return nullcontext()

    def close(self) -> None:
        return None
